/**
 * student_service.h - Student directory business logic.
 *
 * Owns the SQL and turns database rows into JSON. Controllers stay thin and
 * never touch libpq or column names.
 */
#ifndef LMS_STUDENT_SERVICE_H
#define LMS_STUDENT_SERVICE_H

#include <stddef.h>

#include "database/db.h"

/** Maximum length of any single editable student field. */
#define STUDENT_FIELD_MAX 256

/**
 * Editable fields used by create/update. All remain text so JSON parsing and
 * validation live in the service. An empty string means "not provided": create
 * falls back to the schema defaults, update skips the column. `name`, `email`
 * and `student_id` are required on create (and in updates that include them).
 */
typedef struct {
  char name[STUDENT_FIELD_MAX];
  char email[STUDENT_FIELD_MAX];
  char student_id[STUDENT_FIELD_MAX];
  char branch[STUDENT_FIELD_MAX];
  char program[STUDENT_FIELD_MAX];
  char semester[STUDENT_FIELD_MAX]; /* positive integer >= 1, as text */
  char contact[STUDENT_FIELD_MAX];
  char joined_date[STUDENT_FIELD_MAX]; /* YYYY-MM-DD or empty */
  char status[STUDENT_FIELD_MAX];      /* 'active' | 'suspended' or empty */
} StudentMutate;

typedef enum {
  STUDENT_LIST_OK = 0,
  STUDENT_LIST_DB_UNAVAILABLE,  /* no database configured/connected */
  STUDENT_LIST_QUERY_FAILED,    /* the query itself failed */
  STUDENT_LIST_BUFFER_TOO_SMALL /* result did not fit the output buffer */
} StudentListStatus;

typedef enum {
  STUDENT_GET_OK = 0,
  STUDENT_GET_NOT_FOUND,        /* no student with the requested id */
  STUDENT_GET_DB_UNAVAILABLE,   /* no database configured/connected */
  STUDENT_GET_QUERY_FAILED,     /* the query itself failed */
  STUDENT_GET_BUFFER_TOO_SMALL  /* result did not fit the output buffer */
} StudentGetStatus;

/** Default and maximum page size for student searches. */
#define STUDENTS_DEFAULT_LIMIT 100
#define STUDENTS_MAX_LIMIT 500

/**
 * Optional filters for a student search. All fields are optional; a zeroed
 * struct (or NULL) means "first page, no filters".
 */
typedef struct {
  const char *q;        /* case-insensitive match on name OR email OR student_id */
  const char *branch;   /* exact branch match */
  int limit;            /* rows per page; <= 0 -> STUDENTS_DEFAULT_LIMIT */
  int offset;           /* rows to skip; < 0 -> 0 */
} StudentListQuery;

/**
 * Load every student from public.students, ordered by name, as JSON.
 * Equivalent to student_service_search() with no filters.
 *
 * On STUDENT_LIST_OK the output buffer holds {"students":[...]}.
 *
 * @param db       database handle
 * @param out      output buffer
 * @param out_size size of out
 * @param errbuf   receives server-side error detail (log it, don't send it)
 * @param errlen   size of errbuf
 */
StudentListStatus student_service_list(Database *db, char *out, size_t out_size,
                                       char *errbuf, size_t errlen);

/**
 * Load a page of students with optional filters, ordered by name.
 *
 * On success the output holds {"students":[...],"limit":L,"offset":O}. Values
 * are bound as query parameters, so filters cannot inject SQL.
 *
 * @param db       database handle
 * @param query    filters and paging (may be NULL for defaults)
 * @param out      output buffer
 * @param out_size size of out
 * @param errbuf   receives server-side error detail (log it, don't send it)
 * @param errlen   size of errbuf
 */
StudentListStatus student_service_search(Database *db, const StudentListQuery *query,
                                         char *out, size_t out_size, char *errbuf,
                                         size_t errlen);

/**
 * Load a single student by id as JSON.
 *
 * On STUDENT_GET_OK the output buffer holds {"student":{...}}. A missing id is
 * reported as STUDENT_GET_NOT_FOUND (not an error).
 *
 * @param db       database handle
 * @param id       student id (must not be NULL or empty)
 * @param out      output buffer
 * @param out_size size of out
 * @param errbuf   receives server-side error detail (log it, don't send it)
 * @param errlen   size of errbuf
 */
StudentGetStatus student_service_get(Database *db, const char *id, char *out,
                                     size_t out_size, char *errbuf, size_t errlen);

typedef enum {
  STUDENT_CREATE_OK = 0,
  STUDENT_CREATE_BAD_INPUT,        /* name/email/student_id missing or a value is invalid */
  STUDENT_CREATE_DUPLICATE,        /* email or student_id already exists (UNIQUE) */
  STUDENT_CREATE_DB_UNAVAILABLE,   /* no database configured/connected */
  STUDENT_CREATE_QUERY_FAILED      /* the query itself failed */
} StudentCreateStatus;

/**
 * Insert a new student. The id is generated by the database
 * (gen_random_uuid()::text). On STUDENT_CREATE_OK, id_out receives the new row
 * id so the caller can load the full profile with student_service_get().
 */
StudentCreateStatus student_service_create(Database *db, const StudentMutate *student,
                                           char *id_out, size_t id_size, char *errbuf,
                                           size_t errlen);

typedef enum {
  STUDENT_UPDATE_OK = 0,
  STUDENT_UPDATE_NOT_FOUND,      /* no student with the requested id */
  STUDENT_UPDATE_BAD_INPUT,      /* no editable fields or a value is invalid */
  STUDENT_UPDATE_DUPLICATE,      /* email or student_id already exists (UNIQUE) */
  STUDENT_UPDATE_DB_UNAVAILABLE, /* no database configured/connected */
  STUDENT_UPDATE_QUERY_FAILED    /* the query itself failed */
} StudentUpdateStatus;

/** Update only the provided fields of a student; at least one must be set. */
StudentUpdateStatus student_service_update(Database *db, const char *id,
                                           const StudentMutate *student, char *errbuf,
                                           size_t errlen);

typedef enum {
  STUDENT_DELETE_OK = 0,
  STUDENT_DELETE_NOT_FOUND,      /* no student with the requested id */
  STUDENT_DELETE_DB_UNAVAILABLE, /* no database configured/connected */
  STUDENT_DELETE_QUERY_FAILED    /* the query itself failed */
} StudentDeleteStatus;

/**
 * Delete a student by id. Transactions/reservations/fines reference students
 * with ON DELETE CASCADE, so past activity is removed with the profile.
 */
StudentDeleteStatus student_service_delete(Database *db, const char *id, char *errbuf,
                                           size_t errlen);

#endif /* LMS_STUDENT_SERVICE_H */
